function question(id, prompt, options, key, topic, solution, figures = {}) {
  const labels = id % 2 ? 'ABCDE' : 'FGHJK';
  return {
    id, prompt, key, topic, ...solution, ...figures,
    choices: options.map((option, index) => {
      const label = labels[index];
      return option.figure ? { label, ...option } : { label, content: Array.isArray(option) ? option : [option] };
    }),
  };
}

